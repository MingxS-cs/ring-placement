"""Source-isolated splits and geometry-preserving scene augmentation."""
from __future__ import annotations

from dataclasses import dataclass
import copy
import json
from pathlib import Path

import numpy as np


def rotate_xy(vector, angle: float) -> np.ndarray:
    vector = np.asarray(vector, dtype=np.float64)
    c, s = np.cos(angle), np.sin(angle)
    return vector @ np.array([[c, s], [-s, c]])


def split_episodes(episodes: list[dict], seed: int = 20261014) -> dict[str, list[dict]]:
    """Freeze source membership before any descendants are generated."""
    episodes = sorted(episodes, key=lambda e: e["episode_id"])
    ids = [e["episode_id"] for e in episodes]
    if len(set(ids)) != len(ids):
        raise ValueError("Original episode IDs must be unique")
    groups = sorted({e["scene_group"] for e in episodes})
    if len(groups) < 2:
        raise ValueError("Need at least two source scene groups for held-out scene evaluation")
    challenge = [copy.deepcopy(e) for e in episodes if e["scene_group"] == groups[-1]]
    ordinary = [copy.deepcopy(e) for e in episodes if e["scene_group"] != groups[-1]]
    if len(ordinary) < 6:
        raise ValueError("Need at least six ordinary source episodes")
    rng = np.random.default_rng(seed)
    rng.shuffle(ordinary)
    nval = max(2, round(len(ordinary) * .15))
    ntest = max(2, round(len(ordinary) * .15))
    result = {"train": ordinary[nval + ntest:], "val": ordinary[:nval],
              "test": ordinary[nval:nval + ntest], "ood_test": challenge}
    for split, group in result.items():
        for ep in group:
            ep["split"] = split
    return result


def augment_episode(episode: dict, rng: np.random.Generator, split: str,
                    angle_limit: float = np.pi / 6, translation_limit: float = .010,
                    start_jitter: float = .001, identity: bool = False) -> dict:
    """Transform scene positions; action labels are regenerated by physical rollout.

    Geometry is never scaled. Rotation is about the bearing, then both objects
    translate together. Planar endpoint offsets co-rotate. Tool orientation is a
    documented simulator convention for the symmetric ring, not video recovery.
    """
    ep = copy.deepcopy(episode)
    angle = 0.0 if identity else float(rng.uniform(-angle_limit, angle_limit))
    translation = np.zeros(2) if identity else rng.uniform(-translation_limit, translation_limit, 2)
    jitter = np.zeros(2) if identity else rng.uniform(-start_jitter, start_jitter, 2)
    bearing = np.asarray(episode["bearing_xy_m"], dtype=float)
    delta = np.asarray(episode["ring_xy_m"], dtype=float) - bearing
    ep["bearing_xy_m"] = (bearing + translation).tolist()
    ep["ring_xy_m"] = (bearing + translation + rotate_xy(delta, angle) + jitter).tolist()
    ep["final_offset_xy_m"] = rotate_xy(episode.get("final_offset_xy_m", [0., 0.]), angle).tolist()
    ep.update(source_episode_id=episode["episode_id"], split=split, geometry_scale=1.0,
              augmentation={"angle_rad": angle, "translation_m": translation.tolist(),
                            "start_jitter_m": jitter.tolist(), "identity": identity},
              action_label_source="new_MuJoCo_teacher_rollout_after_scene_transform")
    return ep


def make_configurations(splits: dict, counts: dict[str, int], seed: int = 20261014,
                        angle_limit: float = np.pi / 6, translation_limit: float = .010,
                        start_jitter: float = .001) -> dict[str, list[dict]]:
    result = {}
    for split, episodes in splits.items():
        rng = np.random.default_rng(np.random.SeedSequence([seed, list(splits).index(split)]))
        configs = []
        for ep in episodes:
            for i in range(counts.get(split, 1)):
                child = augment_episode(ep, rng, split, angle_limit=angle_limit,
                                        translation_limit=translation_limit, start_jitter=start_jitter,
                                        identity=i == 0)
                child["configuration_id"] = f"{ep['episode_id']}_{split}_{i:03d}"
                child["reset_seed"] = int(rng.integers(0, 2**31 - 1))
                configs.append(child)
        result[split] = configs
    return result


def validate_lineage(configurations: dict) -> None:
    owners = {}
    for split, group in configurations.items():
        for ep in group:
            source = ep["source_episode_id"]
            if source in owners and owners[source] != split:
                raise ValueError(f"Source leakage: {source} belongs to multiple splits")
            if ep["split"] != split:
                raise ValueError("Configuration split does not match its container")
            owners[source] = split


def noisy_observation(observation, rng: np.random.Generator, std: float = .0002):
    """Noisy position measurements; physical state, phases and labels unchanged."""
    obs = np.array(observation, dtype=np.float32, copy=True)
    if obs.shape != (30,):
        raise ValueError("Expected the documented 30-element simulator observation")
    if not np.isfinite(std) or std < 0:
        raise ValueError("Noise standard deviation must be finite and nonnegative")
    command = obs[:3] + obs[15:18]
    perturbation = np.clip(rng.normal(0, std, 9), -3*std, 3*std).astype(np.float32)
    obs[:9] += perturbation
    obs[9:12] = obs[3:6] - obs[0:3]
    obs[12:15] = obs[6:9] - obs[3:6]
    obs[15:18] = command - obs[:3]
    return obs


@dataclass
class Normalizer:
    mean: np.ndarray
    std: np.ndarray

    @classmethod
    def fit(cls, training_values, min_std=1e-4):
        values = np.asarray(training_values, dtype=np.float32)
        if values.ndim != 2 or len(values) == 0 or not np.isfinite(values).all():
            raise ValueError("Normalizer requires finite, nonempty 2D training values")
        return cls(values.mean(axis=0), np.maximum(values.std(axis=0), min_std).astype(np.float32))

    def transform(self, values):
        return (np.asarray(values, dtype=np.float32) - self.mean) / self.std

    def as_dict(self):
        return {"mean": self.mean.tolist(), "std": self.std.tolist()}

    @classmethod
    def from_dict(cls, value):
        return cls(np.array(value["mean"], dtype=np.float32), np.array(value["std"], dtype=np.float32))


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
