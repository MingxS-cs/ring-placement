"""Rebind blind metadata to numerically identical, regenerated JSON files.

Only original endpoints, original optical motion and metadata are read. The
blinded trajectory annotation file is never opened by this helper.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def rebind(real, motion, destination):
    destination = Path(destination)
    if destination.exists():
        raise FileExistsError('Reproduction receipt is immutable')
    original_real, original_motion = 'data/real_episodes.json', 'data/real_motion.json'
    original_receipt = 'outputs/v4_holdout_review/freeze_receipt.json'
    old, regenerated = read(original_real), read(real)
    if old != regenerated:
        raise ValueError('Regenerated endpoint measurements differ; this is a new experiment')
    old_motion, regenerated_motion = read(original_motion), read(motion)
    if regenerated_motion.get('endpoint_manifest_sha256') != sha(real):
        raise ValueError('Regenerated optical motion is not bound to regenerated endpoints')
    for value in (old_motion, regenerated_motion):
        value.pop('endpoint_manifest_sha256', None)
    if old_motion != regenerated_motion:
        raise ValueError('Regenerated optical labels differ; this is a new experiment')
    receipt = read(original_receipt)
    if (receipt['endpoint_manifest_sha256'] != sha(original_real)
            or receipt['existing_motion_sha256'] != sha(original_motion)
            or receipt['source_sha256'] != regenerated['source']['sha256']):
        raise ValueError('Original source receipt is inconsistent')
    receipt.update(endpoint_manifest_sha256=sha(real), existing_motion_sha256=sha(motion),
                   reproduction_original_receipt_sha256=sha(original_receipt),
                   reproduction_note='Endpoint and motion JSON values verified exactly equal to delivered '
                   'measurements, excluding the updated endpoint byte binding; only regenerated byte hashes '
                   'change. Original blind labels are untouched and unopened by this helper.')
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open('x', encoding='utf-8') as stream:
        stream.write(json.dumps(receipt, indent=2, sort_keys=True)+'\n')
    print('Regenerated endpoint and optical labels match delivered values; metadata receipt rebound.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--real', required=True)
    parser.add_argument('--motion', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    rebind(args.real, args.motion, args.output)
